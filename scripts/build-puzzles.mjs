import { createHash } from "node:crypto";
import { readdir, unlink, writeFile } from "node:fs/promises";
import { puzzles } from "../lib/puzzle-generator.js";
const catalog = puzzles.map((p) => ({
  ...p,
  slots: p.slots.map((s) => [
    s.word, s.cells[0].x, s.cells[0].y, s.dx, s.dy,
  ]),
}));
const json = JSON.stringify(catalog);
const hash = createHash("sha256").update(json).digest("hex").slice(0, 16);
const filename = `puzzles.${hash}.json`;
const publicDir = new URL("../public/", import.meta.url);
for (const name of await readdir(publicDir)) {
  if (/^puzzles\.[a-f0-9]{16}\.json$/.test(name) && name !== filename)
    await unlink(new URL(name, publicDir));
}
await writeFile(new URL(filename, publicDir), json + "\n");
await writeFile(new URL("../lib/puzzle-catalog.js", import.meta.url),
  `// Generated by scripts/build-puzzles.mjs.\nimport catalog from "../public/${filename}" with { type: "json" };\nexport default catalog;\nexport const catalogUrl = "/${filename}";\n`);
